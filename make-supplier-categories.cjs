// Builds SEED-supplier-categories.sql from the Procurement folder's
// suppliers.md: each supplier's "Buys" words, and its categories: those
// words split at the commas, first letter a capital (Heinrich, 20 Oct 2026:
// the 12 broad categories went; see setup-procurement-7-supplier-categories-
// words.sql, which does the same to suppliers already loaded).
//
//   node make-supplier-categories.cjs SEED-supplier-categories.sql
//
// Matched to the app's supplier list by name (the five near-names as in
// make-procurement-seed.cjs). Fills a supplier only while its categories or
// buys are still empty, so nothing typed in the app is overwritten. Safe on
// both databases, safe to run twice. Prints which suppliers got no
// category, for Heinrich to place by hand.

const fs = require("fs");
const DIR = "C:/Users/Heinrich/OneDrive/4.APPS/3.PROCUREMENT/";
const SAME_AS = {
  "ambro": "Ambro Steel",
  "euro steel": "Eurosteel",
  "trm supplies": "TRM Supplies (Pty) Ltd",
  "yomi supply chain": "Yomi",
  "dynamic sc": "Dynamic Powdercoaters",
};

// The 12 broad categories' rules, no longer used (20 Oct 2026); kept so the
// history of SEED-supplier-categories.sql at 546b7d4 can be read.
const RULES = [
  ["Steel & sections", /\b(steel|tubes?|pipes?|sections?|plates?|bar|en8|hardox|wear plate|metals?|mesh|screens)\b/i],
  ["Stainless & non-ferrous", /\b(stainless|aluminium|copper|brass)\b/i],
  ["Cutting & machining (subcontract)", /\b(laser cutting|profile cutting|tube cutting|tube bending|machining|manufacturing|fabrications?|gland plates|door frames|plate forming|rolling|nestings|job work)\b/i],
  ["Fasteners & hardware", /\b(fasteners?|bolts?|hardware|hinges|locks|gas struts|castors|springs|wire forms|honeycomb|doors)\b/i],
  ["Tools & abrasives", /\b(tools?|tooling|cutting tools|inserts|abrasives|zirc|bandsaw|cnc parts|tool holders|industrial supplies)\b/i],
  ["Welding, consumables & PPE", /\b(welding|consumables|ppe|workwear|lubricants|sealants|adhesives|tape|filament)\b/i],
  ["Electrical & controls", /\b(electrical|control gear|enclosures|batteries|radios)\b/i],
  ["Pumps, hydraulics & piping", /\b(hydraulic|pumps?|valves|pipe fittings|irrigation|spray nozzles|filters|air cleaners|compressor)\b/i],
  ["Coatings & finishing", /\b(powder coating|coatings?|paint|galvanising|polishing|treatment chemicals|chromadek)\b/i],
  ["Plastics, rubber & packaging", /\b(plastics?|rubber|packaging|boxes|boards)\b/i],
  ["Machine service & transport", /\b(service|repairs?|spares|load testing|transport|relocation|machine moves|lifting|generator|truck|inspection|testing)\b/i],
  ["IT, security & office", /\b(it|printers|computer|security|cctv|software|barcodes)\b/i],
];

const [outFile] = process.argv.slice(2);
if (!outFile) {
  console.error("usage: node make-supplier-categories.cjs <output.sql>");
  process.exit(1);
}

const cells = (line) => line.trim().replace(/^\|/, "").replace(/\|$/, "").split("|").map((c) => c.trim());
const lines = fs.readFileSync(DIR + "suppliers.md", "utf8").split(/\r?\n/).filter((l) => l.trim().startsWith("|"));
const header = cells(lines[0]).map((h) => h.toLowerCase());
const rows = lines.slice(2).map(cells).map((r) => Object.fromEntries(header.map((h, i) => [h, r[i] ?? ""])));

const bySupplier = new Map();
for (const r of rows) {
  if (!r.supplier) continue;
  const name = SAME_AS[r.supplier.trim().toLowerCase()] || r.supplier.trim();
  if (!bySupplier.has(name)) bySupplier.set(name, new Set());
  for (const b of (r.buys || "").split(",").map((x) => x.trim()).filter(Boolean)) bySupplier.get(name).add(b);
}

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const values = [];
const unplaced = [];
for (const [name, buysSet] of bySupplier) {
  const buys = [...buysSet].join(", ");
  const text = buys || name;
  void text;
  const seen = new Set();
  const cats = [...buysSet]
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .filter((w) => !seen.has(w.toLowerCase()) && seen.add(w.toLowerCase()));
  if (!cats.length) unplaced.push(`${name}${buys ? ` (${buys})` : ""}`);
  values.push(`  (${q(name)}, ${q(buys)}, array[${cats.map(q).join(", ")}]::text[])`);
}

const sql = `-- What we buy from each supplier: suppliers.md's "Buys" words and the broad
-- categories they fall under. Generated by make-supplier-categories.cjs on
-- ${new Date().toISOString().slice(0, 10)} (${bySupplier.size} suppliers, ${bySupplier.size - unplaced.length} with categories).
-- Fills only a supplier whose categories or buys are still empty. Needs
-- setup-procurement-6-supplier-categories.sql first. Safe to run twice.
-- Select nothing before pressing Run.

drop table if exists pg_temp.seed_buys;
create temporary table seed_buys (name text, buys text, categories text[]);
insert into seed_buys values
${values.join(",\n")};

update public.master_suppliers m set
  buys = case when m.buys = '' then s.buys else m.buys end,
  categories = case when m.categories = '{}' then s.categories else m.categories end
from seed_buys s
where lower(trim(m.name)) = lower(trim(s.name));

select count(*) filter (where categories <> '{}') || ' suppliers with a category, '
       || count(*) filter (where buys <> '') || ' with what we buy, of ' || count(*) as result
from public.master_suppliers;
`;
fs.writeFileSync(outFile, sql);
console.log(`${bySupplier.size} suppliers, ${unplaced.length} with no category:`);
for (const u of unplaced) console.log("  " + u);
