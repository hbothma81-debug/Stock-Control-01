// Builds the SQL that loads the Procurement folder's registers into the app:
//   suppliers.md -> the supplier list (master_suppliers, its contacts,
//                   account no and terms), adding the suppliers it lacks
//   requests.md  -> the quote request register (procurement_requests)
//
//   node make-procurement-seed.cjs <owner email> <output.sql>
//
// <owner email> is the app sign-in of whoever owns Drawings@ersupplies.co.za
// (Heinrich): requests sent from it become his alone. Requests sent from
// sales@ belong to no one, so everyone with the Procurement tick sees them.
//
// Re-run it on the day the page goes live, so the data is that day's. The
// SQL is safe to run twice: nothing already there is overwritten, and a
// supplier's empty email, phone, account no or terms are filled only while
// still empty.
//
// Heinrich's answers, 19 Oct 2026: add the suppliers the app lacks; these
// five are the app supplier of the other name (the app's name is kept);
// the two Macsteel divisions are their own suppliers; NO bank details.

const fs = require("fs");
const DIR = "C:/Users/Heinrich/OneDrive/4.APPS/3.PROCUREMENT/";
const SAME_AS = {
  "ambro": "Ambro Steel",
  "euro steel": "Eurosteel",
  "trm supplies": "TRM Supplies (Pty) Ltd",
  "yomi supply chain": "Yomi",
  "dynamic sc": "Dynamic Powdercoaters",
};
const DRAWINGS = "drawings@ersupplies.co.za";
const SALES = "sales@ersupplies.co.za";

const [ownerEmail, outFile] = process.argv.slice(2);
if (!ownerEmail || !outFile) {
  console.error("usage: node make-procurement-seed.cjs <owner email> <output.sql>");
  process.exit(1);
}

const cells = (line) => line.trim().replace(/^\|/, "").replace(/\|$/, "").split("|").map((c) => c.trim());
function table(file) {
  const lines = fs.readFileSync(DIR + file, "utf8").split(/\r?\n/).filter((l) => l.trim().startsWith("|"));
  const header = cells(lines[0]).map((h) => h.toLowerCase());
  return lines.slice(2).map(cells).map((row) => Object.fromEntries(header.map((h, i) => [h, row[i] ?? ""])));
}
const q = (s) => (s == null || s === "" ? "''" : "'" + String(s).replace(/'/g, "''") + "'");
const appName = (name) => SAME_AS[name.trim().toLowerCase()] || name.trim();
const BANK = /\b(bank|absa|fnb|capitec|nedbank|standard bank|branch code|acc(ount)? ?no\.? ?\d{6,})\b/i;

// ---- Suppliers: one entry per supplier, contacts gathered under it ----
const suppliers = new Map();
for (const r of table("suppliers.md")) {
  if (!r.supplier) continue;
  const name = appName(r.supplier);
  if (!suppliers.has(name)) suppliers.set(name, { name, rows: [] });
  suppliers.get(name).rows.push(r);
}
const pick = (rows, key, prefer) =>
  (prefer && rows.find((r) => prefer(r) && r[key]))?.[key] || rows.find((r) => r[key])?.[key] || "";
const isSales = (r) => /sales/i.test(r.role);

const supplierValues = [...suppliers.values()].map((s) => {
  const terms = pick(s.rows, "terms");
  return `  (${q(s.name)}, ${q(pick(s.rows, "email", isSales))}, ${q(pick(s.rows, "phone", isSales))}, ${q(pick(s.rows, "account no"))}, ${terms ? q(terms) : "null"})`;
});
const contactValues = [...suppliers.values()].flatMap((s) =>
  s.rows.filter((r) => r.email).map((r) => `  (${q(s.name)}, ${q(r.contact || r.role || "")}, ${q(r.email)})`)
);

// ---- Requests ----
const requests = table("requests.md").filter((r) => /^PR-\d+/.test(r.no));
for (const r of requests) {
  if (BANK.test(r.notes)) {
    console.error(`${r.no}: its notes mention bank details; take them out of requests.md first.`);
    process.exit(1);
  }
}
const mailboxOf = (r) => (/sales@ersupplies\.co\.za/i.test(r.notes) ? SALES : DRAWINGS);
const requestValues = requests.map((r) => {
  const supplier = appName((r.supplier.split(/[(,]/)[0] || r.supplier).trim());
  const mailbox = mailboxOf(r);
  return `  (${q(r.no)}, ${q(mailbox)}, ${mailbox === DRAWINGS ? "true" : "false"}, ${q(supplier)}, ${q(r["contact email"])}, ${q(r.item)}, ${q(r.qty)}, ${q(r["old quote"])}, ${q(r.status)}, ${r.date ? q(r.date) : "null"}, ${r["waiting since"] ? q(r["waiting since"]) : "null"}, ${Number(r.chases) || 0}, ${q(r.notes)}, ${q(r.ref)})`;
});

const sql = `-- Loads the Procurement folder's registers into the app. Generated by
-- make-procurement-seed.cjs on ${new Date().toISOString().slice(0, 10)} from suppliers.md
-- (${suppliers.size} suppliers) and requests.md (${requests.length} requests).
-- Requests from ${DRAWINGS} belong to ${ownerEmail}.
--
-- Adds the suppliers the app lacks, with their contacts; fills a supplier's
-- email, phone, account no and terms only while still empty; adds each
-- request once (by its PR number). Nothing already there is overwritten.
-- No bank details anywhere.
--
-- Needs setup-procurement-1-access.sql to -3. Safe to run more than once.
-- Select nothing before pressing Run.

do $do$
begin
  if not exists (select 1 from public.profiles where lower(email) = lower(${q(ownerEmail)})) then
    raise exception 'No app sign-in with the email %: tell Claude', ${q(ownerEmail)};
  end if;
end $do$;

drop table if exists pg_temp.seed_suppliers;
create temporary table seed_suppliers (name text, email text, phone text, account_no text, terms text);
insert into seed_suppliers values
${supplierValues.join(",\n")};

insert into public.master_suppliers (id, name, email, phone, account_no, terms)
select 'pr' || left(md5(lower(s.name)), 6), s.name, s.email, s.phone, s.account_no, s.terms
from seed_suppliers s
where not exists (select 1 from public.master_suppliers m where lower(trim(m.name)) = lower(trim(s.name)))
on conflict (id) do nothing;

update public.master_suppliers m set
  email = case when m.email = '' then s.email else m.email end,
  phone = case when m.phone = '' then s.phone else m.phone end,
  account_no = case when m.account_no = '' then s.account_no else m.account_no end,
  terms = coalesce(m.terms, s.terms)
from seed_suppliers s
where lower(trim(m.name)) = lower(trim(s.name));

drop table if exists pg_temp.seed_contacts;
create temporary table seed_contacts (supplier text, name text, email text);
insert into seed_contacts values
${contactValues.join(",\n")};

insert into public.master_supplier_contacts (id, supplier_id, name, email)
select 'pc' || left(md5(m.id || lower(c.email)), 6), m.id, c.name, c.email
from seed_contacts c
join public.master_suppliers m on lower(trim(m.name)) = lower(trim(c.supplier))
where not exists (select 1 from public.master_supplier_contacts x
                  where x.supplier_id = m.id and lower(x.email) = lower(c.email))
on conflict (id) do nothing;

drop table if exists pg_temp.seed_requests;
create temporary table seed_requests (pr_number text, mailbox text, owned boolean, supplier text,
  contact_email text, item text, qty text, old_quote text, status text, requested date,
  waiting_since date, chases integer, notes text, conversation_id text);
insert into seed_requests values
${requestValues.join(",\n")};

insert into public.procurement_requests (pr_number, mailbox, owner_id, supplier_id, supplier_name,
  contact_email, item, qty, old_quote, status, requested_at, waiting_since, chases, notes,
  conversation_id, created_by, updated_by)
select r.pr_number, r.mailbox,
       case when r.owned then (select p.id from public.profiles p where lower(p.email) = lower(${q(ownerEmail)}) limit 1) end,
       m.id, coalesce(m.name, r.supplier), r.contact_email, r.item, r.qty, r.old_quote, r.status,
       r.requested::timestamptz, r.waiting_since, r.chases, r.notes, nullif(r.conversation_id, ''),
       'requests.md', 'requests.md'
from seed_requests r
left join public.master_suppliers m on lower(trim(m.name)) = lower(trim(r.supplier))
on conflict (pr_number) do nothing;

select 'suppliers' as what, count(*)::text || ' on the list, ' || count(*) filter (where account_no <> '') || ' with an account no' as result
from public.master_suppliers
union all
select 'requests', count(*)::text || ' (' || string_agg(pr_number || ' ' || status, ', ' order by pr_number) || ')'
from public.procurement_requests;
`;
fs.writeFileSync(outFile, sql);
console.log(`${suppliers.size} suppliers, ${contactValues.length} contacts, ${requests.length} requests -> ${outFile}`);
